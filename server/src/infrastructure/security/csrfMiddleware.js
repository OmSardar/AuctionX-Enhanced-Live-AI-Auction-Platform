/**
 * Custom CSRF Protection Middleware (Double-Submit Cookie Pattern with Signed HMAC Cross-Origin Fallback)
 * Replaces the deprecated `csurf` package.
 *
 * How it works:
 * 1. GET /api/csrf-token → generates a cryptographically signed HMAC token,
 *    sets it in a cookie (SameSite=None; Secure for cross-origin HTTPS) AND returns it in JSON.
 * 2. On POST/PUT/PATCH/DELETE requests:
 *    a) If the `_csrf` cookie is present: compares the header token with the cookie value
 *       (classic Double-Submit Cookie).
 *    b) If the cookie is absent (modern browsers like Safari ITP, Brave, Chrome blocking 3rd-party
 *       cookies across decoupled domains such as vercel.app -> onrender.com): validates the
 *       cryptographic HMAC signature and freshness of the header token.
 */

const crypto = require("crypto");

const CSRF_COOKIE_NAME = "_csrf";
const CSRF_HEADER_NAME = "x-csrf-token";

// Methods that don't need CSRF protection
const SAFE_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);

// Webhook, telemetry & authenticated GraphQL endpoints exempt from CSRF
const CSRF_EXEMPT_PATHS = [
  "/api/payment/webhook",
  "/api/webhooks/razorpay",
  "/api/seller/subscriptions/webhook",
  "/api/track",
  "/api/soap/transactions",
  "/api/graphql",
];

/**
 * Retrieves the secret key used for HMAC signing of CSRF tokens.
 */
function getCsrfSecret() {
  return (
    process.env.CSRF_SECRET ||
    process.env.JWT_SECRET ||
    "auctionx-csrf-signing-secret-default-key-32chars"
  );
}

/**
 * Check if the current request is exempt from CSRF protection
 */
function isCsrfExempt(req) {
  const urlPath = req.originalUrl || req.path || "";
  return CSRF_EXEMPT_PATHS.some(
    (exemptPath) =>
      urlPath === exemptPath ||
      urlPath.startsWith(`${exemptPath}/`) ||
      urlPath.startsWith(`${exemptPath}?`)
  );
}

/**
 * Generate a cryptographically secure CSRF token with signed HMAC payload.
 * Structure: <nonce>.<timestamp>.<hmacSignature>
 */
function generateToken() {
  const nonce = crypto.randomBytes(16).toString("hex");
  const timestamp = Date.now().toString();
  const payload = `${nonce}.${timestamp}`;
  const hmac = crypto
    .createHmac("sha256", getCsrfSecret())
    .update(payload)
    .digest("hex");
  return `${payload}.${hmac}`;
}

/**
 * Verifies if a given token was generated by our server and has not expired.
 * Lifetime: 24 hours (86,400,000 ms).
 */
function verifySignedToken(token) {
  if (typeof token !== "string") return false;
  const parts = token.split(".");
  if (parts.length !== 3) return false;
  const [nonce, timestampStr, signature] = parts;
  if (!nonce || !timestampStr || !signature) return false;

  const timestamp = parseInt(timestampStr, 10);
  if (isNaN(timestamp)) return false;

  const maxAge = 24 * 60 * 60 * 1000; // 24 hours
  const now = Date.now();
  const clockSkewLeeway = 5 * 60 * 1000; // 5-minute clock drift tolerance
  if (timestamp - now > clockSkewLeeway || now - timestamp > maxAge) {
    return false;
  }

  const payload = `${nonce}.${timestampStr}`;
  const expectedHmac = crypto
    .createHmac("sha256", getCsrfSecret())
    .update(payload)
    .digest("hex");

  if (signature.length !== expectedHmac.length) return false;
  return crypto.timingSafeEqual(Buffer.from(signature), Buffer.from(expectedHmac));
}

/**
 * Middleware: attach csrfToken() helper to the request object
 * and validate tokens on unsafe methods.
 */
function csrfProtection(req, res, next) {
  // Attach a helper to generate/retrieve the token
  let token = req.cookies[CSRF_COOKIE_NAME];

  req.csrfToken = () => {
    if (!token || !verifySignedToken(token)) {
      token = generateToken();
    }
    return token;
  };

  // Safe methods don't need validation
  if (SAFE_METHODS.has(req.method)) {
    return next();
  }

  // Webhook endpoints are exempt from CSRF (authenticated via cryptographic signature)
  if (isCsrfExempt(req)) {
    return next();
  }

  const cookieToken = req.cookies[CSRF_COOKIE_NAME];
  const headerToken = req.headers[CSRF_HEADER_NAME];

  // If header token is missing entirely, reject immediately
  if (!headerToken) {
    return res.status(403).json({
      success: false,
      message: "CSRF token missing",
    });
  }

  // Double-Submit Cookie: when the cookie is present, validate against it
  if (cookieToken) {
    if (cookieToken.length !== headerToken.length) {
      return res.status(403).json({
        success: false,
        message: "Invalid CSRF token",
      });
    }

    const cookieBuf = Buffer.from(cookieToken);
    const headerBuf = Buffer.from(headerToken);

    if (!crypto.timingSafeEqual(cookieBuf, headerBuf)) {
      return res.status(403).json({
        success: false,
        message: "Invalid CSRF token",
      });
    }

    return next();
  }

  // Cross-origin fallback for decoupled SPA deployments (Vercel -> Render)
  // where third-party cookies are blocked or partitioned by browsers.
  // Validate the server-signed HMAC token in the header.
  if (verifySignedToken(headerToken)) {
    return next();
  }

  return res.status(403).json({
    success: false,
    message: "CSRF token missing",
  });
}

/**
 * Route handler: GET /api/csrf-token
 * Sets the CSRF cookie and returns the token in JSON.
 */
function csrfTokenRoute(req, res) {
  const token = req.csrfToken();

  const isSecure =
    process.env.NODE_ENV === "production" ||
    req.secure ||
    req.headers["x-forwarded-proto"] === "https";

  const cookieOptions = {
    httpOnly: false, // Must be readable by client-side JS
    secure: isSecure,
    sameSite: isSecure ? "none" : "lax",
    maxAge: 86400000, // 24 hours
  };

  res.cookie(CSRF_COOKIE_NAME, token, cookieOptions);

  // Also set it as XSRF-TOKEN for Angular/axios auto-detection
  res.cookie("XSRF-TOKEN", token, cookieOptions);

  res.json({ csrfToken: token });
}

module.exports = {
  csrfProtection,
  csrfTokenRoute,
  generateToken,
  verifySignedToken,
  isCsrfExempt,
  CSRF_EXEMPT_PATHS,
};
